-- 1. STUDENTS TABLE
CREATE TABLE IF NOT EXISTS public.students (
    student_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    pin VARCHAR(20) NOT NULL DEFAULT ''
);

-- 2. ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.items (
    item_id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    condition VARCHAR(50) NOT NULL,
    rental_price_per_day NUMERIC(12, 2) NOT NULL CHECK(rental_price_per_day > 0),
    lender_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK(status IN ('AVAILABLE', 'REQUESTED', 'BORROWED'))
);

-- 3. BORROW REQUESTS TABLE
CREATE TABLE IF NOT EXISTS public.borrow_requests (
    request_id VARCHAR(20) PRIMARY KEY,
    item_id VARCHAR(20) NOT NULL REFERENCES public.items(item_id) ON DELETE RESTRICT,
    borrower_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    lender_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    duration_days INTEGER NOT NULL CHECK(duration_days > 0),
    requested_on DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED'))
);

-- 4. TRANSACTIONS TABLE
CREATE TABLE IF NOT EXISTS public.transactions (
    transaction_id VARCHAR(20) PRIMARY KEY,
    request_id VARCHAR(20) NOT NULL REFERENCES public.borrow_requests(request_id) ON DELETE RESTRICT,
    item_id VARCHAR(20) NOT NULL REFERENCES public.items(item_id) ON DELETE RESTRICT,
    borrower_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    lender_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    due_date DATE NOT NULL,
    duration_days INTEGER NOT NULL CHECK(duration_days > 0),
    daily_rent NUMERIC(12, 2) NOT NULL CHECK(daily_rent > 0),
    rental_amount NUMERIC(12, 2) NOT NULL,
    commission NUMERIC(12, 2) NOT NULL,
    lender_earnings NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'BORROWED' CHECK(status IN ('BORROWED', 'RETURN_PENDING', 'COMPLETED', 'CANCELLED')),
    returned_on DATE,
    late_days INTEGER NOT NULL DEFAULT 0,
    late_fee NUMERIC(12, 2) NOT NULL DEFAULT 0.0,
    return_condition VARCHAR(50) NOT NULL DEFAULT '',
    damage_charge NUMERIC(12, 2) NOT NULL DEFAULT 0.0
);

-- 5. RETURN RECORDS TABLE
CREATE TABLE IF NOT EXISTS public.return_records (
    return_id VARCHAR(20) PRIMARY KEY,
    transaction_id VARCHAR(20) NOT NULL REFERENCES public.transactions(transaction_id) ON DELETE RESTRICT,
    item_id VARCHAR(20) NOT NULL REFERENCES public.items(item_id) ON DELETE RESTRICT,
    borrower_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    lender_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    return_date DATE NOT NULL,
    return_condition VARCHAR(50) NOT NULL,
    late_days INTEGER NOT NULL DEFAULT 0,
    late_fee NUMERIC(12, 2) NOT NULL DEFAULT 0.0,
    damage_charge NUMERIC(12, 2) NOT NULL DEFAULT 0.0,
    status VARCHAR(20) NOT NULL DEFAULT 'RETURN_SUBMITTED' CHECK(status IN ('RETURN_SUBMITTED', 'CONFIRMED'))
);

-- 6. CANCELLATIONS TABLE
CREATE TABLE IF NOT EXISTS public.cancellations (
    cancellation_id VARCHAR(20) PRIMARY KEY,
    actor_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    request_id VARCHAR(20),
    transaction_id VARCHAR(20),
    reason TEXT NOT NULL DEFAULT '',
    stage VARCHAR(30) NOT NULL,
    cancelled_on DATE NOT NULL
);

-- 7. AUDIT HISTORY LOG TABLE
CREATE TABLE IF NOT EXISTS public.audit_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(50) NOT NULL,
    transaction_id VARCHAR(20),
    request_id VARCHAR(20),
    student_id VARCHAR(20) NOT NULL REFERENCES public.students(student_id) ON DELETE RESTRICT,
    event_date DATE NOT NULL,
    details TEXT NOT NULL DEFAULT ''
);

-- INDEXES FOR PERFORMANCE
CREATE INDEX IF NOT EXISTS idx_items_lender ON public.items(lender_id);
CREATE INDEX IF NOT EXISTS idx_items_status ON public.items(status);
CREATE INDEX IF NOT EXISTS idx_requests_item ON public.borrow_requests(item_id);
CREATE INDEX IF NOT EXISTS idx_requests_borrower ON public.borrow_requests(borrower_id);
CREATE INDEX IF NOT EXISTS idx_requests_status ON public.borrow_requests(status);
CREATE INDEX IF NOT EXISTS idx_transactions_borrower ON public.transactions(borrower_id);
CREATE INDEX IF NOT EXISTS idx_transactions_lender ON public.transactions(lender_id);
CREATE INDEX IF NOT EXISTS idx_transactions_status ON public.transactions(status);

